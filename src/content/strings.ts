/** Turns a validation message key from a schema into user text. */
export function errorText(key: string | undefined): string | undefined {
  if (!key) return undefined;
  const text = (strings.errors as Record<string, unknown>)[key];
  return typeof text === 'string' ? text : strings.common.somethingWrong;
}
